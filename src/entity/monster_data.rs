pub const MONSTER_LEVELS: [usize; 41] = [
    8, 19, 34, 49, 59, 73, 81, 90, 96, 105, 113, 118, 128, 135, 143, 153, 160, 164, 167, 174, 178, 182, 187, 193, 197, 202, 208, 212, 215, 221, 227, 231, 235, 239, 244, 250, 256, 261, 265, 270, 277
];


/// Canonical Umoria monster selection algorithm.
/// Selects an authentic creature index (0..277) suitable for the dungeon depth.
pub fn get_monster_for_level<R: rand::Rng>(level: u32, rng: &mut R) -> usize {
    if level == 0 {
        return rng.gen_range(0..MONSTER_LEVELS[0]);
    }

    let mut target_level = level.min(40);

    // 1 in 50 chance of higher level creature ('nasty')
    if rng.gen_range(0..50) == 0 {
        let boost = rng.gen_range(1..=5);
        target_level = (target_level + boost).min(40);
    } else {
        let num = MONSTER_LEVELS[target_level as usize] - MONSTER_LEVELS[0];
        if num > 0 {
            let i = rng.gen_range(0..num);
            let j = rng.gen_range(0..num);
            let chosen = i.max(j);
            target_level = CREATURES_LIST[chosen + MONSTER_LEVELS[0]].level as u32;
        }
    }

    let target_lvl_idx = target_level as usize;
    if target_lvl_idx == 0 {
        return rng.gen_range(0..MONSTER_LEVELS[0]);
    }

    let low = MONSTER_LEVELS[target_lvl_idx - 1];
    let high = MONSTER_LEVELS[target_lvl_idx];
    if high > low {
        rng.gen_range(low..high)
    } else {
        low
    }
}
